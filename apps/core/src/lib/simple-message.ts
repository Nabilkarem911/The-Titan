/**
 * تصنيف الرسائل البسيطة — مشترك بين كل المسارات (HTTP + تليجرام).
 *
 * ⚠️ السبب: كان كل مسار بيعالج الرسالة كأنها مهمة كاملة.
 * المقاس الفعلي: «صباح الخير» = 5 خطوات · 72 ثانية · 15,569 توكن.
 * مسار تليجرام كان مكتوب فيه maxSteps = 10 بالثابت، فالتصنيف ما كانش بيوصله.
 *
 * الرسالة البسيطة (سلام · شكر · سؤال قصير) مش محتاجة خطوات — رد واحد كفاية.
 */

const SIMPLE_PATTERNS: RegExp[] = [
  /^\s*(صباح|مساء|نهار)\s*(الخير|النور|الخير\s*يا)/,
  /^\s*(ها+|هلا|أهلا|اهلا|أهلاً|سلام|سلامو|السلام)/,
  /^\s*(ازيك|إزيك|إزاي\s*حالك|اخبارك|أخبارك|عامل\s*(اي|إيه)|عامل\s*ايه|إيه\s*أخبارك)/,
  /^\s*(شكرا|شكراً|تسلم|متشكر|جزاك|ربنا\s*يكرمك|تسلم\s*ايدك)/,
  /^\s*(تمام|ماشي|اوك|أوك|اوكي|طيب|معلش|خلاص|حلو|زي\s*الفل|الحمد\s*لله)/,
  /^\s*(ها\s*يا|يا\s*حب|يا\s*صاحبي|يا\s*قلب|كمل|براحتك|زي\s*ما\s*تحب)\s*[\w\s!؟.]{0,15}$/,
  /^\s*(hi|hello|hey|ok|okay|thanks|thank you|good\s*(morning|evening))\s*[!.]?\s*$/i,
];

/** كلمات تدل على إن فيه مهمة حقيقية → تستاهل خطوات */
const TASK_WORDS = /(اكتب|اعمل|ابحث|حلل|صلح|برمج|لخص|راجع|انشر|ارسل|نفذ|شغل|كود|ملف|دالة|سكربت|تقرير|جدول|احسب|قارن|ترجم|صمم|طور|ثبت|نصب|deploy|fix|build)/;

export function isSimpleMessage(prompt: string): boolean {
  const p = (prompt ?? '').trim();
  if (!p || p.length > 60) return false;
  if (SIMPLE_PATTERNS.some((r) => r.test(p))) return true;
  // سؤال قصير جدًا من غير أي كلمة مهمة
  return p.length <= 25 && !TASK_WORDS.test(p);
}

/** الخطوات المناسبة للرسالة: 1 للبسيطة · 4 لغيرها */
export function stepsForMessage(prompt: string): number {
  return isSimpleMessage(prompt) ? 1 : 4;
}
