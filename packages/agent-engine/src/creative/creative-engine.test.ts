import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { CreativeEngine } from './creative-engine.js';
import { MockEchoProvider } from '../mockLlmProvider.js';
import { join } from 'node:path';
import { rm, mkdir } from 'node:fs/promises';

const TEST_DIR = join(process.cwd(), 'tmp', 'creative-test');

describe('CreativeEngine', () => {
  let engine: CreativeEngine;

  beforeEach(async () => {
    await mkdir(TEST_DIR, { recursive: true });
    engine = new CreativeEngine(new MockEchoProvider(), TEST_DIR);
  });

  afterEach(async () => {
    try { await rm(TEST_DIR, { recursive: true, force: true }); } catch {}
  });

  it('should generate creative code (p5.js)', async () => {
    const result = await engine.generate({
      prompt: 'flowing particle system',
      type: 'code',
      style: 'p5.js',
    });
    expect(result.type).toBe('code');
    expect(result.content).toBeDefined();
    expect(result.content!).toContain('AI-Generated by Titan');
    expect(result.metadata.model).toBe('p5.js');
    expect(result.metadata.tokensUsed).toBeGreaterThan(0);
  });

  it('should generate creative code (glsl)', async () => {
    const result = await engine.generate({
      prompt: 'plasma effect',
      type: 'code',
      style: 'glsl',
    });
    expect(result.metadata.style).toBe('glsl');
    expect(result.content!).toContain('AI-Generated by Titan');
  });

  it('should generate creative code (three.js)', async () => {
    const result = await engine.generate({
      prompt: 'rotating cube',
      type: 'code',
      style: 'three.js',
    });
    expect(result.metadata.style).toBe('three.js');
  });

  it('should use default p5.js when no style specified', async () => {
    const result = await engine.generate({
      prompt: 'colorful waves',
      type: 'code',
    });
    expect(result.metadata.model).toBe('p5.js');
  });

  it('should generate music code fallback when no API key', async () => {
    const result = await engine.generate({
      prompt: 'ambient soundscape',
      type: 'music',
      style: 'ambient',
      duration: 30,
    });
    expect(result.type).toBe('music');
    expect(result.filePath).toBeDefined();
    expect(result.metadata.model).toBe('tonejs-fallback');
    expect(result.metadata.watermark).toBe('AI-Generated by Titan');
  });

  it('should throw on image generation without API key', async () => {
    await expect(engine.generate({
      prompt: 'sunset',
      type: 'image',
    })).rejects.toThrow('No API key');
  });

  it('should throw on video generation without API key', async () => {
    await expect(engine.generate({
      prompt: 'ocean waves',
      type: 'video',
    })).rejects.toThrow('No API key');
  });

  it('should include watermark in all generated content', async () => {
    const result = await engine.generate({
      prompt: 'test art',
      type: 'code',
    });
    expect(result.metadata.watermark).toBe('AI-Generated by Titan');
    expect(result.content!).toContain('AI-Generated by Titan');
  });

  it('should record style preferences', () => {
    engine.recordStylePreference('user1', 'cyberpunk', 'neon colors', 8);
    engine.recordStylePreference('user1', 'cyberpunk', 'neon colors', 9);
    const prefs = engine.getStylePreferences('user1');
    expect(prefs).toHaveLength(1);
    expect(prefs[0].styleName).toBe('cyberpunk');
    expect(prefs[0].samples).toBe(2);
    expect(prefs[0].rating).toBeGreaterThan(8);
  });

  it('should track multiple styles per user', () => {
    engine.recordStylePreference('user1', 'cyberpunk', 'neon', 9);
    engine.recordStylePreference('user1', 'watercolor', 'soft', 6);
    const prefs = engine.getStylePreferences('user1');
    expect(prefs).toHaveLength(2);
  });

  it('should recommend highest-rated style', () => {
    engine.recordStylePreference('user1', 'cyberpunk', 'neon', 9);
    engine.recordStylePreference('user1', 'watercolor', 'soft', 6);
    engine.recordStylePreference('user1', 'minimalist', 'clean', 7);
    const recommended = engine.getRecommendedStyle('user1');
    expect(recommended).toBe('cyberpunk');
  });

  it('should return null recommended style for new user', () => {
    expect(engine.getRecommendedStyle('unknown')).toBeNull();
  });

  it('should return empty preferences for unknown user', () => {
    expect(engine.getStylePreferences('unknown')).toHaveLength(0);
  });

  it('should critique creative work with multiple reviewers', async () => {
    const result = await engine.generate({
      prompt: 'test art',
      type: 'code',
    });
    const reviewers = [new MockEchoProvider(), new MockEchoProvider()];
    const critiques = await engine.critique(result, reviewers);
    expect(critiques).toHaveLength(2);
    expect(critiques[0].rating).toBeGreaterThanOrEqual(1);
    expect(critiques[0].rating).toBeLessThanOrEqual(10);
  });

  it('should handle critique with no reviewers', async () => {
    const result = await engine.generate({
      prompt: 'test',
      type: 'code',
    });
    const critiques = await engine.critique(result, []);
    expect(critiques).toHaveLength(0);
  });

  it('should handle critique with failing reviewer', async () => {
    const result = await engine.generate({
      prompt: 'test',
      type: 'code',
    });
    const failingReviewer = {
      complete: async () => { throw new Error('Reviewer unavailable'); },
    };
    const critiques = await engine.critique(result, [failingReviewer as any]);
    expect(critiques).toHaveLength(0);
  });

  it('should calculate generation time', async () => {
    const result = await engine.generate({
      prompt: 'test',
      type: 'code',
    });
    expect(result.metadata.generationTimeMs).toBeGreaterThanOrEqual(0);
  });

  it('should cleanup old files gracefully', async () => {
    const cleaned = await engine.cleanupOldFiles();
    expect(cleaned).toBeGreaterThanOrEqual(0);
  });

  it('should throw for unknown creative type', async () => {
    await expect(engine.generate({
      prompt: 'test',
      type: 'unknown' as any,
    })).rejects.toThrow('Unknown creative type');
  });
});
