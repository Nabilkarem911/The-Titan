import { getLogger } from '@titan/logging';
import { incCounter, observeHistogram } from '@titan/observability';
import { randomUUID } from 'node:crypto';
import { mkdir, writeFile, readdir, unlink, stat } from 'node:fs/promises';
import { join } from 'node:path';
import type { LlmProvider } from '../types.js';

const log = getLogger().child({ component: 'creative-engine' });

type CreativeMediaType = 'image' | 'music' | 'video' | 'code';

interface CreativeGenerationOptions {
  prompt: string;
  type: CreativeMediaType;
  style?: string;
  width?: number;
  height?: number;
  duration?: number;
  temperature?: number;
  seed?: number;
}

interface CreativeResult {
  id: string;
  type: CreativeMediaType;
  prompt: string;
  filePath?: string;
  content?: string;
  mimeType: string;
  metadata: {
    model: string;
    tokensUsed: number;
    generationTimeMs: number;
    watermark: string;
    style?: string;
  };
}

interface StylePreference {
  id: string;
  userId: string;
  styleName: string;
  description: string;
  preferences: Record<string, unknown>;
  rating: number;
  samples: number;
  createdAt: Date;
}

interface CreativeCritique {
  reviewer: string;
  rating: number;
  strengths: string[];
  weaknesses: string[];
  suggestions: string[];
}

const MAX_VIDEO_TIMEOUT_MS = 60_000;
const MAX_FILE_SIZE_BYTES = 50 * 1024 * 1024;
const TEMP_DIR = join(process.cwd(), 'tmp', 'creative');
const AUTO_CLEAN_HOURS = 24;
const WATERMARK = 'AI-Generated by Titan';

export class CreativeEngine {
  private llm: LlmProvider;
  private styles: Map<string, StylePreference[]> = new Map();
  private tempDir: string;

  constructor(llm: LlmProvider, tempDir?: string) {
    this.llm = llm;
    this.tempDir = tempDir ?? TEMP_DIR;
  }

  async generate(opts: CreativeGenerationOptions): Promise<CreativeResult> {
    const startTime = Date.now();
    const id = randomUUID();

    await this.ensureTempDir();

    let result: CreativeResult;

    switch (opts.type) {
      case 'image':
        result = await this.generateImage(opts, id, startTime);
        break;
      case 'music':
        result = await this.generateMusic(opts, id, startTime);
        break;
      case 'video':
        result = await this.generateVideo(opts, id, startTime);
        break;
      case 'code':
        result = await this.generateCode(opts, id, startTime);
        break;
      default:
        throw new Error(`Unknown creative type: ${opts.type}`);
    }

    incCounter('creative_generations', 'Creative content generations', 1, { type: opts.type });
    observeHistogram('creative_generation_time_ms', 'Creative generation time', result.metadata.generationTimeMs, undefined, { type: opts.type });

    return result;
  }

  private async generateImage(
    opts: CreativeGenerationOptions,
    id: string,
    startTime: number,
  ): Promise<CreativeResult> {
    const apiKey = process.env['CREATIVE_API_KEY'] ?? process.env['LLM_API_KEY'] ?? process.env['OPENAI_API_KEY'];
    const baseUrl = process.env['CREATIVE_BASE_URL'] ?? process.env['LLM_BASE_URL'] ?? 'https://api.openai.com/v1';
    const model = process.env['IMAGE_MODEL'] ?? 'dall-e-3';

    if (!apiKey) {
      throw new Error('No API key configured for image generation');
    }

    const fullPrompt = opts.style ? `${opts.prompt}, style: ${opts.style}` : opts.prompt;
    const size = `${opts.width ?? 1024}x${opts.height ?? 1024}`;

    try {
      const response = await fetch(`${baseUrl}/images/generations`, {
        method: 'POST',
        headers: {
          'Authorization': `Bearer ${apiKey}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          model,
          prompt: `${fullPrompt}\n\nWatermark: ${WATERMARK}`,
          n: 1,
          size,
          quality: 'standard',
        }),
      });

      if (!response.ok) {
        throw new Error(`Image API error: ${response.status} ${await response.text()}`);
      }

      const data = await response.json() as { data: Array<{ url?: string; b64_json?: string }> };
      const item = data.data?.[0];

      if (!item) throw new Error('No image data returned');

      let filePath: string | undefined;
      if (item.b64_json) {
        filePath = join(this.tempDir, `${id}.png`);
        await writeFile(filePath, Buffer.from(item.b64_json, 'base64'));
      } else if (item.url) {
        const imgResponse = await fetch(item.url);
        const buffer = await imgResponse.arrayBuffer();
        filePath = join(this.tempDir, `${id}.png`);
        await writeFile(filePath, Buffer.from(buffer));
      }

      return {
        id,
        type: 'image',
        prompt: opts.prompt,
        filePath,
        mimeType: 'image/png',
        metadata: {
          model,
          tokensUsed: 0,
          generationTimeMs: Date.now() - startTime,
          watermark: WATERMARK,
          style: opts.style,
        },
      };
    } catch (err) {
      log.error({ err }, 'image generation failed');
      throw err;
    }
  }

  private async generateMusic(
    opts: CreativeGenerationOptions,
    id: string,
    startTime: number,
  ): Promise<CreativeResult> {
    const apiKey = process.env['MUSIC_API_KEY'] ?? process.env['CREATIVE_API_KEY'];
    const baseUrl = process.env['MUSIC_BASE_URL'] ?? 'https://api.suno.ai/v1';
    const model = process.env['MUSIC_MODEL'] ?? 'suno-v4';

    if (!apiKey) {
      // Fallback: generate Tone.js code for simple beats
      log.warn('no music API key — generating Tone.js code fallback');
      return this.generateMusicCodeFallback(opts, id, startTime);
    }

    try {
      const response = await fetch(`${baseUrl}/generations`, {
        method: 'POST',
        headers: {
          'Authorization': `Bearer ${apiKey}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          prompt: opts.prompt,
          duration: opts.duration ?? 30,
          style: opts.style ?? 'pop',
        }),
      });

      if (!response.ok) {
        throw new Error(`Music API error: ${response.status}`);
      }

      const data = await response.json() as { audio_url?: string; id?: string };
      let filePath: string | undefined;

      if (data.audio_url) {
        const audioResponse = await fetch(data.audio_url);
        const buffer = await audioResponse.arrayBuffer();
        filePath = join(this.tempDir, `${id}.mp3`);
        await writeFile(filePath, Buffer.from(buffer));
      }

      return {
        id,
        type: 'music',
        prompt: opts.prompt,
        filePath,
        mimeType: 'audio/mpeg',
        metadata: {
          model,
          tokensUsed: 0,
          generationTimeMs: Date.now() - startTime,
          watermark: WATERMARK,
          style: opts.style,
        },
      };
    } catch (err) {
      log.error({ err }, 'music generation failed — using code fallback');
      return this.generateMusicCodeFallback(opts, id, startTime);
    }
  }

  private async generateMusicCodeFallback(
    opts: CreativeGenerationOptions,
    id: string,
    startTime: number,
  ): Promise<CreativeResult> {
    const completion = await this.llm.complete([
      {
        role: 'system',
        content: 'You are a music composer. Generate Tone.js code that creates a musical piece. Output ONLY JavaScript code, no explanation.',
      },
      {
        role: 'user',
        content: `Compose music for: "${opts.prompt}". Style: ${opts.style ?? 'ambient'}. Duration: ${opts.duration ?? 30}s. Use Tone.js library.`,
      },
    ], { temperature: opts.temperature ?? 0.7, maxTokens: 2000 });

    const code = `// ${WATERMARK}\n// Prompt: ${opts.prompt}\n// Style: ${opts.style ?? 'ambient'}\n\n${completion.content}`;
    const filePath = join(this.tempDir, `${id}.js`);
    await writeFile(filePath, code);

    return {
      id,
      type: 'music',
      prompt: opts.prompt,
      filePath,
      mimeType: 'text/javascript',
      metadata: {
        model: 'tonejs-fallback',
        tokensUsed: completion.tokensUsed,
        generationTimeMs: Date.now() - startTime,
        watermark: WATERMARK,
        style: opts.style,
      },
    };
  }

  private async generateVideo(
    opts: CreativeGenerationOptions,
    id: string,
    startTime: number,
  ): Promise<CreativeResult> {
    const apiKey = process.env['VIDEO_API_KEY'] ?? process.env['CREATIVE_API_KEY'];
    const baseUrl = process.env['VIDEO_BASE_URL'] ?? 'https://api.sogni.ai/v1';
    const model = process.env['VIDEO_MODEL'] ?? 'sogni-v1';

    if (!apiKey) {
      throw new Error('No API key configured for video generation');
    }

    const timeoutPromise = new Promise<never>((_, reject) =>
      setTimeout(() => reject(new Error('Video generation timeout')), MAX_VIDEO_TIMEOUT_MS),
    );

    try {
      const fetchPromise = fetch(`${baseUrl}/generations`, {
        method: 'POST',
        headers: {
          'Authorization': `Bearer ${apiKey}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          prompt: `${opts.prompt}\n\nWatermark: ${WATERMARK}`,
          duration: opts.duration ?? 5,
          style: opts.style,
        }),
      });

      const response = await Promise.race([fetchPromise, timeoutPromise]);

      if (!response.ok) {
        throw new Error(`Video API error: ${response.status}`);
      }

      const data = await response.json() as { video_url?: string };
      let filePath: string | undefined;

      if (data.video_url) {
        const videoResponse = await fetch(data.video_url);
        const buffer = await videoResponse.arrayBuffer();

        if (buffer.byteLength > MAX_FILE_SIZE_BYTES) {
          throw new Error(`Video file exceeds ${MAX_FILE_SIZE_BYTES} bytes limit`);
        }

        filePath = join(this.tempDir, `${id}.mp4`);
        await writeFile(filePath, Buffer.from(buffer));
      }

      return {
        id,
        type: 'video',
        prompt: opts.prompt,
        filePath,
        mimeType: 'video/mp4',
        metadata: {
          model,
          tokensUsed: 0,
          generationTimeMs: Date.now() - startTime,
          watermark: WATERMARK,
          style: opts.style,
        },
      };
    } catch (err) {
      log.error({ err }, 'video generation failed');
      throw err;
    }
  }

  private async generateCode(
    opts: CreativeGenerationOptions,
    id: string,
    startTime: number,
  ): Promise<CreativeResult> {
    const framework = opts.style ?? 'p5.js';
    const frameworkPrompt = this.getFrameworkPrompt(framework);

    const completion = await this.llm.complete([
      {
        role: 'system',
        content: `You are a generative art coder. Generate ${framework} code that creates visual art. Output ONLY code, no explanation. Add watermark comment: ${WATERMARK}`,
      },
      {
        role: 'user',
        content: `${frameworkPrompt}\n\nCreate generative art for: "${opts.prompt}"\nCanvas: ${opts.width ?? 800}x${opts.height ?? 600}`,
      },
    ], { temperature: opts.temperature ?? 0.8, maxTokens: 3000 });

    const code = `// ${WATERMARK}\n// Prompt: ${opts.prompt}\n// Framework: ${framework}\n\n${completion.content}`;
    const filePath = join(this.tempDir, `${id}.${this.getCodeExtension(framework)}`);
    await writeFile(filePath, code);

    return {
      id,
      type: 'code',
      prompt: opts.prompt,
      filePath,
      content: code,
      mimeType: 'text/javascript',
      metadata: {
        model: framework,
        tokensUsed: completion.tokensUsed,
        generationTimeMs: Date.now() - startTime,
        watermark: WATERMARK,
        style: framework,
      },
    };
  }

  async critique(
    result: CreativeResult,
    reviewers: LlmProvider[],
  ): Promise<CreativeCritique[]> {
    const critiques: CreativeCritique[] = [];

    for (let i = 0; i < reviewers.length; i++) {
      const reviewer = reviewers[i];
      try {
        const completion = await reviewer.complete([
          {
            role: 'system',
            content: 'You are a creative critic. Evaluate the creative work. Respond in JSON: {"rating": 1-10, "strengths": ["..."], "weaknesses": ["..."], "suggestions": ["..."]}',
          },
          {
            role: 'user',
            content: `Type: ${result.type}\nPrompt: ${result.prompt}\nContent preview: ${result.content?.slice(0, 500) ?? 'binary file'}`,
          },
        ], { temperature: 0.3, maxTokens: 500 });

        const parsed = this.parseCritique(completion.content, `reviewer-${i}`);
        critiques.push(parsed);
      } catch (err) {
        log.warn({ err, reviewer: i }, 'critique failed');
      }
    }

    return critiques;
  }

  recordStylePreference(userId: string, styleName: string, description: string, rating: number): void {
    const existing = this.styles.get(userId) ?? [];
    const pref = existing.find((p) => p.styleName === styleName);

    if (pref) {
      pref.rating = (pref.rating * pref.samples + rating) / (pref.samples + 1);
      pref.samples++;
    } else {
      existing.push({
        id: randomUUID(),
        userId,
        styleName,
        description,
        preferences: {},
        rating,
        samples: 1,
        createdAt: new Date(),
      });
      this.styles.set(userId, existing);
    }

    incCounter('creative_style_recorded', 'Style preferences recorded', 1);
  }

  getStylePreferences(userId: string): StylePreference[] {
    return this.styles.get(userId) ?? [];
  }

  getRecommendedStyle(userId: string): string | null {
    const prefs = this.styles.get(userId);
    if (!prefs || prefs.length === 0) return null;

    const sorted = [...prefs].sort((a, b) => b.rating - a.rating);
    return sorted[0].styleName;
  }

  async cleanupOldFiles(): Promise<number> {
    try {
      const files = await readdir(this.tempDir);
      const now = Date.now();
      const maxAge = AUTO_CLEAN_HOURS * 60 * 60 * 1000;
      let cleaned = 0;

      for (const file of files) {
        const filePath = join(this.tempDir, file);
        const stats = await stat(filePath);
        if (now - stats.mtime.getTime() > maxAge) {
          await unlink(filePath);
          cleaned++;
        }
      }

      if (cleaned > 0) {
        log.info({ cleaned }, 'old creative files cleaned up');
      }

      return cleaned;
    } catch {
      return 0;
    }
  }

  private async ensureTempDir(): Promise<void> {
    try {
      await mkdir(this.tempDir, { recursive: true });
    } catch {
      // dir might already exist
    }
  }

  private getFrameworkPrompt(framework: string): string {
    const prompts: Record<string, string> = {
      'p5.js': 'Use p5.js. Create a sketch with setup() and draw() functions.',
      'glsl': 'Write a GLSL fragment shader. Use uniforms: iTime, iResolution.',
      'three.js': 'Use Three.js. Create a scene with camera, renderer, and animation loop.',
    };
    return prompts[framework] ?? prompts['p5.js'];
  }

  private getCodeExtension(framework: string): string {
    const exts: Record<string, string> = {
      'p5.js': 'js',
      'glsl': 'frag',
      'three.js': 'js',
    };
    return exts[framework] ?? 'js';
  }

  private parseCritique(content: string, reviewer: string): CreativeCritique {
    try {
      const jsonMatch = content.match(/\{[\s\S]*\}/);
      if (!jsonMatch) {
        return { reviewer, rating: 5, strengths: [], weaknesses: [], suggestions: [] };
      }

      const raw = JSON.parse(jsonMatch[0]) as {
        rating?: number;
        strengths?: string[];
        weaknesses?: string[];
        suggestions?: string[];
      };

      return {
        reviewer,
        rating: Math.max(1, Math.min(10, raw.rating ?? 5)),
        strengths: Array.isArray(raw.strengths) ? raw.strengths : [],
        weaknesses: Array.isArray(raw.weaknesses) ? raw.weaknesses : [],
        suggestions: Array.isArray(raw.suggestions) ? raw.suggestions : [],
      };
    } catch {
      return { reviewer, rating: 5, strengths: [], weaknesses: [], suggestions: [] };
    }
  }
}

let globalEngine: CreativeEngine | null = null;

function getCreativeEngine(llm?: LlmProvider): CreativeEngine {
  if (!globalEngine) {
    if (!llm) throw new Error('CreativeEngine not initialized — provide LlmProvider');
    globalEngine = new CreativeEngine(llm);
  }
  return globalEngine;
}

function initCreativeEngine(llm: LlmProvider, tempDir?: string): CreativeEngine {
  globalEngine = new CreativeEngine(llm, tempDir);
  return globalEngine;
}
